let currentLanguage = (typeof window !== 'undefined' && window.localStorage)
  ? (localStorage.getItem('kaamka_language') || 'hi')
  : 'hi';

export function getCurrentLanguage() {
  return currentLanguage;
}

export function t(key) {
  const langDict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['hi'];
  return langDict[key] || TRANSLATIONS['hi'][key] || TRANSLATIONS['en'][key] || key;
}

export function setLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) {
    langCode = 'hi';
  }
  currentLanguage = langCode;
  if (typeof window !== 'undefined' && window.localStorage) {
    localStorage.setItem('kaamka_language', langCode);
  }

  const langObj = SUPPORTED_LANGUAGES.find(l => l.code === langCode);
  const isRtl = langObj ? langObj.isRtl : false;

  if (typeof document !== 'undefined') {
    document.documentElement.lang = langCode;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';

    // Update elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translated = t(key);
      if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
        el.placeholder = translated;
      } else {
        el.textContent = translated;
      }
    });

    // Dispatch language change event for other modules
    window.dispatchEvent(new CustomEvent('kaamka:language_change', { detail: { lang: langCode, isRtl } }));
  }
}
